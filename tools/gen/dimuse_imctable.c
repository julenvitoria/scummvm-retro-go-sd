/*
 * Builds the IMC (bundle ADPCM) decoder's tables of Digital iMUSE (SCUMM v7: The Dig's
 * .bun files) as const data: 22 KB the console keeps in external flash instead of the heap.
 * The loops are BundleCodecs::initializeImcTables()'s (engines/scumm/imuse_digi/
 * dimuse_codecs.cpp), over the IMA ADPCM step table (audio/decoders/adpcm.cpp).
 *
 *   cc -O2 tools/gen/dimuse_imctable.c -o gen && ./gen > dimuse_imctable.c
 */
#include <stdio.h>
#include <stdint.h>

static const int16_t ima[89] = {
	    7,    8,    9,   10,   11,   12,   13,   14,   16,   17,   19,   21,   23,   25,   28,   31,
	   34,   37,   41,   45,   50,   55,   60,   66,   73,   80,   88,   97,  107,  118,  130,  143,
	  157,  173,  190,  209,  230,  253,  279,  307,  337,  371,  408,  449,  494,  544,  598,  658,
	  724,  796,  876,  963, 1060, 1166, 1282, 1411, 1552, 1707, 1878, 2066, 2272, 2499, 2749, 3024,
	 3327, 3660, 4026, 4428, 4871, 5358, 5894, 6484, 7132, 7845, 8630, 9493,10442,11487,12635,13899,
	15289,16818,18500,20350,22385,24623,27086,29794,32767
};

int main(void)
{
	printf("/* generated by tools/gen/dimuse_imctable.c */\n#include <stdint.h>\n");
	printf("const uint8_t gw_imc_table[89] = {");
	for (int pos = 0; pos <= 88; ++pos) {
		int put = 1;
		int32_t v = ((ima[pos] * 4) / 7) / 2;
		while (v != 0) { v /= 2; put++; }
		if (put < 3) put = 3;
		if (put > 8) put = 8;
		printf("%s%d", pos ? "," : "", put - 1);
	}
	printf("};\nconst uint32_t gw_imc_table2[89 * 64] = {\n");
	for (int pos = 0; pos <= 88; ++pos) {
		for (int n = 0; n < 64; n++) {
			int32_t count = 32, put = 0, v = ima[pos];
			do {
				if (count & n) put += v;
				count /= 2;
				v /= 2;
			} while (count != 0);
			printf("%d,", put);
		}
		printf("\n");
	}
	printf("};\n");
	return 0;
}
