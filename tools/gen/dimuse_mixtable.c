/*
 * Builds the Digital iMUSE mixer's amplitude and volume-curve tables (SCUMM v7: Full Throttle,
 * The Dig) as a const array, so the console keeps these 213 KB in external flash instead of
 * the heap. The loops are IMuseDigiInternalMixer::init()'s (engines/scumm/imuse_digi/
 * dimuse_internalmixer.cpp), for the parameters the engine uses here: 16-bit output and
 * 6 mixing channels; the engine fills its own copy when they differ (patches/scummvm-slim.patch).
 *
 *   cc -O2 tools/gen/dimuse_mixtable.c -o gen && ./gen > dimuse_mixtable.c
 */
#include <stdio.h>
#include <stdint.h>
#include <string.h>

#define WORDS 16
#define CHANNELS 6

static int32_t t[53376];

int main(void)
{
	int32_t *amp8 = t, *amp12 = t + 2176, *softLMID = t + 45184;
	int amplitudeValue, zeroCenterOffset = 0, n = CHANNELS;
	unsigned softLdenominator, softLnumerator;
	int softLcurValue;
	memset(t, 0, sizeof t);
	for (int i = 0; i < 17; i++) {
		amplitudeValue = -2048 * zeroCenterOffset;
		for (int j = 0; j < 256; j++) {
			((int16_t *)&amp8[i * 128])[j] = (int16_t)(amplitudeValue / 127);
			amplitudeValue += 16 * zeroCenterOffset;
		}
		zeroCenterOffset += 8;
		if (zeroCenterOffset == 8) zeroCenterOffset = 7;
	}
	zeroCenterOffset = 0;
	for (int i = 0; i < 17; i++) {
		amplitudeValue = -2048 * zeroCenterOffset;
		for (int j = 0; j < 4096; j++) {
			((int16_t *)&amp12[i * 2048])[j] = (int16_t)(amplitudeValue / 127);
			amplitudeValue += zeroCenterOffset;
		}
		zeroCenterOffset += 8;
		if (zeroCenterOffset == 8) zeroCenterOffset = 7;
	}
	/* WORDS == 16 */
	softLdenominator = 2047 * n;
	softLnumerator = 0;
	for (int i = 0; i < n * 2048; i++) {
		softLcurValue = softLnumerator / softLdenominator + 1;
		softLcurValue /= 2;
		softLdenominator += n - 1;
		softLnumerator += 65534 * n;
		((int16_t *)softLMID)[i] = (int16_t)softLcurValue;
		((int16_t *)softLMID)[-i - 1] = -1 - (int16_t)softLcurValue;
	}
	printf("/* generated by tools/gen/dimuse_mixtable.c -- do not edit */\n#include <stdint.h>\n");
	printf("const int gw_dimuse_mixtable_words = %d, gw_dimuse_mixtable_channels = %d;\n", WORDS, CHANNELS);
	printf("const int32_t gw_dimuse_mixtable[53376] = {\n");
	for (int i = 0; i < 53376; i++) printf("%d,%s", t[i], (i % 16) == 15 ? "\n" : "");
	printf("};\n");
	return 0;
}
